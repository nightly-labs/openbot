import type { ComponentType } from "react";
import Svg, { Circle as SvgCircle, Path as SvgPath, type SvgProps } from "react-native-svg";

type IconNode = readonly (readonly [string, Readonly<Record<string, string | number>>])[];

export interface IconProps extends SvgProps {
  size?: number | string;
  absoluteStrokeWidth?: boolean;
}

export type AppIcon = ComponentType<IconProps>;
/** The name the screens used for an icon component when the set was Lucide. */
export type LucideIcon = AppIcon;

const LUCIDE_DEFAULT_STROKE = 2;
const HUGEICONS_LINE_SCALE = 0.85;
const DROPPED = new Set(["key", "stroke", "strokeWidth"]);

function pathProps(attributes: Readonly<Record<string, string | number>>): Record<string, string | number> {
  const props: Record<string, string | number> = {};
  for (const [name, value] of Object.entries(attributes)) if (!DROPPED.has(name)) props[name] = value;
  return props;
}

function hugeicon(node: IconNode): AppIcon {
  const parts = node.map(([tag, attributes], index) => ({ tag, index, props: pathProps(attributes) }));
  return function Icon({ size = 24, color = "currentColor", strokeWidth, absoluteStrokeWidth, ...rest }: IconProps) {
    const base = Number(strokeWidth ?? LUCIDE_DEFAULT_STROKE) * HUGEICONS_LINE_SCALE;
    const line = absoluteStrokeWidth === true ? (base * 24) / Number(size) : base;
    return (
      <Svg
        width={size}
        height={size}
        viewBox="0 0 24 24"
        fill="none"
        stroke={color}
        strokeWidth={line}
        strokeLinecap="round"
        strokeLinejoin="round"
        {...rest}
      >
        {parts.map((part) =>
          part.tag === "circle" ? (
            <SvgCircle key={part.index} {...part.props} />
          ) : (
            <SvgPath key={part.index} {...part.props} />
          ),
        )}
      </Svg>
    );
  };
}

