export function teamCapabilitiesForProtocol(protocol: number | null | undefined): readonly TeamCurrentCapability[] {
  if (protocol === null || protocol === undefined || protocol < 7) return TEAM_BOOTSTRAP_CAPABILITIES;
  if (protocol >= 10) return TEAM_CURRENT_CAPABILITIES;
  if (protocol === 9) return TEAM_PROTOCOL_V10_BASELINE_CAPABILITIES;
  return protocol === 8 ? TEAM_PROTOCOL_V8_CURRENT_CAPABILITIES : TEAM_PROTOCOL_V7_CURRENT_CAPABILITIES;
}
export function teamCapabilitiesVisibleToProtocol<T extends string>(capabilities: readonly T[], protocol: number): T[] {
  const newest = protocol >= 10 ? 10 : protocol >= 9 ? 9 : 8;
  return capabilities.filter((capability) => capabilitySince(capability) <= newest);
}
export function legacyTeamCapabilities(capabilities: readonly string[]): string[] {
  return capabilities.filter((capability) => capabilitySince(capability) === 1);
}

export function supportsTeamCapability(
  capabilities: ReadonlySet<string> | readonly string[],
  capability: TeamCurrentCapability,
): boolean {
  return "has" in capabilities ? capabilities.has(capability) : capabilities.includes(capability);
}

export function expandTeamCapabilitiesV10(lists: TeamCapabilitiesV10): string[] {
  const absent = new Set(lists.absent);
  return [
    ...new Set([
      ...TEAM_PROTOCOL_V10_BASELINE_CAPABILITIES.filter((capability) => !absent.has(capability)),
      ...lists.capabilities,
    ]),
  ];
}

export function encodeTeamCapabilitiesV10(capabilities: readonly string[]): TeamCapabilitiesV10 {
  const served = new Set(capabilities);
  return {
    capabilities: [...served].filter(
      (capability) =>
        !TEAM_PROTOCOL_V10_BASELINE_SET.has(capability) || capability === TEAM_LONG_CAPABILITY_LISTS_CAPABILITY,
    ),
    absent: TEAM_PROTOCOL_V10_BASELINE_CAPABILITIES.filter((capability) => !served.has(capability)),
  };
}

export function teamCapabilityHeaders(
  protocol: number | null | undefined,
  capabilities: readonly string[],
): Record<string, string> {
  const lists = teamCapabilityLists(protocol, capabilities);
  return {
    [TEAM_CAPABILITIES_HEADER]: lists.capabilities.join(","),
    ...(lists.absent ? { [TEAM_ABSENT_CAPABILITIES_HEADER]: lists.absent.join(",") } : {}),
  };
}

export function teamCapabilityLists(
  protocol: number | null | undefined,
  capabilities: readonly string[],
): { capabilities: string[]; absent?: string[] } {
  if (protocol === null || protocol === undefined || protocol < TEAM_PROTOCOL_V10)
    return { capabilities: [...capabilities] };
  const lists = encodeTeamCapabilitiesV10(capabilities);
  return lists.absent.length ? lists : { capabilities: lists.capabilities };
}

export function decodeTeamProtocolSupportExpanded(value: unknown): TeamProtocolSupportV9 {
  if (!hasTeamProtocolV10Lists(value)) return decodeTeamProtocolSupportV9(value);
  const support = decodeTeamProtocolSupportV10(value);
  return {
    appVersion: support.appVersion,
    protocol: support.protocol,
    capabilities: expandTeamCapabilitiesV10(support),
  };
}

export async function readTeamHostCompatibility(
  read: () => Promise<unknown>,
  client: TeamProtocolSupportV1["protocol"] = TEAM_WEBRTC_CLIENT_PROTOCOL,
) {
  const first = await read();
  const support = decodeTeamProtocolSupportExpanded(first);
  const negotiated = teamWebRtcClientProtocol(support.protocol, client);
  if (hasTeamProtocolV10Lists(first) || negotiated.update || (negotiated.protocol ?? 0) < TEAM_PROTOCOL_V10)
    return { support, negotiated };
  return { support: decodeTeamProtocolSupportExpanded(await read()), negotiated };
}

function capabilitySince(capability: string): TeamCapabilityPlacement["since"] {
  return TEAM_CAPABILITY_PLACEMENTS.get(capability)?.since ?? 1;
}

function capabilitiesWhere(test: (placement: TeamCapabilityPlacement) => boolean): readonly TeamCurrentCapability[] {
  return TEAM_CAPABILITY_REGISTRY.filter(([, placement]) => test(placement)).map(([capability]) => capability);
}
