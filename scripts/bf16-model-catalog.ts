// Writes src/backend/bf16-models.ts from bf16.ai's public OpenAI-compatible model catalog.
// Pi has no built-in bf16 provider, so this list is what the bf16 extension registers.
// Run it before a release: `bun scripts/bf16-model-catalog.ts`. Needs the network and no key.
import assert from "node:assert/strict";
import { writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { agentProviderDescriptor } from "@openbot/contracts/agent-providers";
import { Schema } from "effect";
import { BF16_MODELS_URL, Bf16CatalogEnvelope, bf16Models } from "../src/backend/bf16-catalog";

const OUT = resolve(import.meta.dirname, "../src/backend/bf16-models.ts");
const MIN_MODELS = 4;

const response = await fetch(BF16_MODELS_URL, { headers: { Accept: "application/json" } });
assert.equal(response.ok, true, `bf16.ai answered ${response.status}.`);
const envelope = Schema.decodeUnknownSync(Bf16CatalogEnvelope)(await response.json());
const models = bf16Models(envelope.data);
const defaultModel = agentProviderDescriptor("bf16").defaultModel;

assert.ok(models.length >= MIN_MODELS, `Only ${models.length} bf16.ai models can run an agent.`);
assert.ok(
  models.some((model) => model.id === defaultModel),
  `The default bf16.ai model ${defaultModel} is not in the list, or has no tool calling.`,
);

const source = `// Generated by scripts/bf16-model-catalog.ts from ${BF16_MODELS_URL}. Do not edit.
// Fetched ${new Date().toISOString().slice(0, 10)}: ${models.length} of ${envelope.data.length} models can run an agent.
import type { Bf16Model } from "./bf16-catalog";

export const BF16_MODELS = ${JSON.stringify(models, null, 2)} as const satisfies readonly Bf16Model[];
`;
await writeFile(OUT, source);
process.stdout.write(`Wrote ${models.length} bf16.ai models to ${OUT}.\n`);
