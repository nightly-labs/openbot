// Writes src/backend/venice-models.ts from Venice's public text model list. Pi has no Venice provider,
// so this list is what the Venice extension registers. Run it before a release:
// `bun scripts/venice-model-catalog.ts`. Needs the network and no key.
import assert from "node:assert/strict";
import { writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { agentProviderDescriptor } from "@openbot/contracts/agent-providers";
import { Schema } from "effect";
import { VENICE_MODELS_URL, VeniceCatalogEnvelope, veniceModels } from "../src/backend/venice-catalog";

const OUT = resolve(import.meta.dirname, "../src/backend/venice-models.ts");
/** Venice listed 138 text models on 2026-11-09. Far fewer means a broken response, not a smaller catalog. */
const MIN_MODELS = 20;

const response = await fetch(VENICE_MODELS_URL, { headers: { Accept: "application/json" } });
assert.equal(response.ok, true, `Venice answered ${response.status}.`);
const envelope = Schema.decodeUnknownSync(VeniceCatalogEnvelope)(await response.json());
const models = veniceModels(envelope.data);
const defaultModel = agentProviderDescriptor("venice").defaultModel;

assert.ok(models.length >= MIN_MODELS, `Only ${models.length} Venice models can run an agent.`);
assert.ok(
  models.some((model) => model.id === defaultModel),
  `The default Venice model ${defaultModel} is not in the list, or has no tool calling.`,
);

const source = `// Generated by scripts/venice-model-catalog.ts from ${VENICE_MODELS_URL}. Do not edit.
// Fetched ${new Date().toISOString().slice(0, 10)}: ${models.length} of ${envelope.data.length} text models can run an agent.
import type { VeniceModel } from "./venice-catalog";

export const VENICE_MODELS = ${JSON.stringify(models, null, 2)} as const satisfies readonly VeniceModel[];
`;
await writeFile(OUT, source);
process.stdout.write(`Wrote ${models.length} Venice models to ${OUT}.\n`);
