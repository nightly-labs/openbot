// Makes and checks `src/main/released-schema-versions.ts`: for each released desktop version, the
// highest `openbot.db` schema version that it can open. The values come from the migration list of
// `src/backend/openbot-database-schema.ts` at each `v<x.y.z>` tag.
//
//   bun scripts/released-schema-versions.ts          checks the table against the tags
//   bun scripts/released-schema-versions.ts --write  writes the table again from the tags
//
// The table is frozen. A version that has this change records its own schema version in the start
// attempts file when it finishes a start (`src/main/start-attempts.ts`), so a new release does not
// need an entry. The check also stops when a tag after LAST_RELEASE does not have this table, because
// that release does not record its schema version. `release.yml` runs the check for each release.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { compareReleaseVersions, parseReleaseVersion } from "../packages/contracts/src/release-version";

const ROOT = resolve(import.meta.dirname, "..");
const TABLE = join(ROOT, "src/main/released-schema-versions.ts");
const SCHEMA_SOURCE = "src/backend/openbot-database-schema.ts";
/** The last release that does not record its schema version. Later releases are not in the table. */
const LAST_RELEASE = "0.72.0";

function git(args: string[]): string {
  return execFileSync("git", args, { cwd: ROOT, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] });
}

/** Tags are filtered to X.Y.Z before they come here, so each one parses. */
function compareVersions(left: string, right: string): number {
  const a = parseReleaseVersion(left);
  const b = parseReleaseVersion(right);
  if (!a || !b) throw new Error(`Not a release version: ${a ? right : left}.`);
  return compareReleaseVersions(a, b);
}

/** The highest schema version that the source of one release can open. 0 when it has no database. */
function highestSchemaVersion(source: string | null, tag: string): number {
  if (source === null) return 0;
  const list = source.indexOf("const MIGRATIONS");
  if (list !== -1) {
    const end = source.indexOf("\n];", list);
    if (end === -1) throw new Error(`${tag}: the migration list has no end.`);
    const baseline = /const BASELINE_SCHEMA_VERSION = (\d+);/.exec(source)?.[1];
    const versions = [...source.slice(list, end).matchAll(/^\s+version: (\d+|BASELINE_SCHEMA_VERSION),$/gm)].map(
      (match) => Number.parseInt(match[1] === "BASELINE_SCHEMA_VERSION" ? (baseline ?? "") : (match[1] ?? ""), 10),
    );
    if (versions.length === 0 || versions.some((version) => !Number.isInteger(version))) {
      throw new Error(`${tag}: the migration list has no valid versions.`);
    }
    return Math.max(...versions);
  }
  // The first releases had one schema version and no migration list.
  const single = /const SCHEMA_VERSION = (\d+);/.exec(source)?.[1];
  if (single) return Number.parseInt(single, 10);
  throw new Error(`${tag}: no schema version found in ${SCHEMA_SOURCE}.`);
}

function tableFromTags(): Map<string, number> {
  const all = git(["tag", "--list", "v*"])
    .split("\n")
    .filter((tag) => /^v\d+\.\d+\.\d+$/.test(tag))
    .map((tag) => tag.slice(1))
    .sort(compareVersions);
  for (const version of all.filter((candidate) => compareVersions(candidate, LAST_RELEASE) > 0)) {
    try {
      git(["cat-file", "-e", `v${version}:src/main/released-schema-versions.ts`]);
    } catch {
      throw new Error(
        `v${version} does not record its schema version. Set LAST_RELEASE to ${version} and run --write.`,
      );
    }
  }
  const tags = all.filter((version) => compareVersions(version, LAST_RELEASE) <= 0);
  if (!tags.includes(LAST_RELEASE)) throw new Error(`Tag v${LAST_RELEASE} is missing. Run git fetch --tags.`);
  const table = new Map<string, number>();
  let previous = 0;
  for (const version of tags) {
    let source: string | null;
    try {
      source = git(["show", `v${version}:${SCHEMA_SOURCE}`]);
    } catch {
      source = null;
    }
    const schema = highestSchemaVersion(source, `v${version}`);
    // A release never opens fewer schema versions than the release before it.
    if (schema < previous) throw new Error(`v${version} has schema ${schema}, less than ${previous} before it.`);
    previous = schema;
    table.set(version, schema);
  }
  return table;
}

function render(table: Map<string, number>): string {
  const rows = [...table].map(([version, schema]) => `  "${version}": ${schema},`).join("\n");
  return `// Generated by \`bun scripts/released-schema-versions.ts --write\` from the release tags. Do not edit.
//
// For each released desktop version up to ${LAST_RELEASE}, the highest \`openbot.db\` schema version that it
// can open. Later versions record their own schema version in the start attempts file.
export const RELEASED_SCHEMA_VERSIONS: Readonly<Record<string, number>> = {
${rows}
};
`;
}

const expected = render(tableFromTags());
if (process.argv.includes("--write")) {
  writeFileSync(TABLE, expected);
  process.stdout.write(`Wrote ${TABLE}.\n`);
} else if (readFileSync(TABLE, "utf8") !== expected) {
  process.stderr.write(`${TABLE} does not match the release tags. Run with --write and check the diff.\n`);
  process.exit(1);
} else {
  process.stdout.write("The released schema table matches the release tags.\n");
}
